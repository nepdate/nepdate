/**
 * Turns data/bikram-sambat.json into packages/core/src/bs/data/years.ts.
 *
 * The JSON anchors the table with an AD date. That AD date is used only here,
 * once, to compute `epochStart` (days since 1970-01-01 of 1 Baisakh of the first
 * year), so the BS code in core never handles an AD date (docs/plan D-001).
 *
 * Run: node scripts/gen-data.ts          write the file
 *      node scripts/gen-data.ts --check  fail if the file is out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface SourceTable {
  anchor: { bs_year: number; ad: string };
  verified_through: number;
  years: Record<string, number[]>;
}

export interface GeneratedTable {
  firstYear: number;
  epochStart: number;
  verifiedThrough: number;
  years: number[][];
}

const DAY_MS = 86_400_000;

/** Days in a verified year. Projected years may be off by one until checked (BS 2096 lists 364). */
const VERIFIED_YEAR_DAYS = [365, 366];
const PROJECTED_YEAR_DAYS = [364, 365, 366, 367];

export function buildTable(source: SourceTable): GeneratedTable {
  const entries = Object.entries(source.years)
    .map(([year, months]) => [Number(year), months] as const)
    .sort(([a], [b]) => a - b);
  const first = entries[0];
  if (!first) {
    throw new Error('The BS table has no years.');
  }
  const firstYear = first[0];

  entries.forEach(([year, months], index) => {
    if (!Number.isInteger(year)) {
      throw new Error(`"${String(year)}" is not a BS year.`);
    }
    if (year !== firstYear + index) {
      throw new Error(`The BS table skips from ${firstYear + index - 1} to ${year}.`);
    }
    if (months.length !== 12) {
      throw new Error(`BS ${year} lists ${months.length} months, not 12.`);
    }
    months.forEach((days, month) => {
      if (!Number.isInteger(days) || days < 29 || days > 32) {
        throw new Error(
          `BS ${year} month ${month + 1} has ${days} days; expected 29–32.`,
        );
      }
    });
    const total = sum(months);
    const allowed =
      year <= source.verified_through ? VERIFIED_YEAR_DAYS : PROJECTED_YEAR_DAYS;
    if (!allowed.includes(total)) {
      throw new Error(`BS ${year} has ${total} days; expected ${allowed.join(' or ')}.`);
    }
  });

  const { bs_year: anchorYear, ad } = source.anchor;
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(ad);
  if (!match || anchorYear < firstYear || anchorYear >= firstYear + entries.length) {
    throw new Error(`The anchor (BS ${anchorYear} = AD ${ad}) is not inside the table.`);
  }
  const anchorEpoch =
    Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3])) / DAY_MS;
  const yearsBeforeAnchor = entries.slice(0, anchorYear - firstYear);
  const epochStart =
    anchorEpoch - sum(yearsBeforeAnchor.map(([, months]) => sum(months)));

  return {
    firstYear,
    epochStart,
    verifiedThrough: source.verified_through,
    years: entries.map(([, months]) => [...months]),
  };
}

export function renderTable(table: GeneratedTable): string {
  const rows = table.years
    .map((months, index) => `    [${months.join(', ')}], // ${table.firstYear + index}`)
    .join('\n');

  return `// Generated by scripts/gen-data.ts from data/bikram-sambat.json. Do not edit by hand.
// Run \`pnpm gen:data\` after changing the JSON.

/** The bundled Bikram Sambat table: month lengths keyed by BS year, no AD dates. */
export interface GeneratedBsData {
  /** The BS year of the first row. */
  readonly firstYear: number;
  /** Days since 1970-01-01 of 1 Baisakh of \`firstYear\`. */
  readonly epochStart: number;
  /** Years after this one are projections, not yet checked against a published calendar. */
  readonly verifiedThrough: number;
  /** Twelve month lengths (Baisakh..Chaitra) per year, starting at \`firstYear\`. */
  readonly years: readonly (readonly number[])[];
}

export const BS_DATA: GeneratedBsData = {
  firstYear: ${table.firstYear},
  epochStart: ${table.epochStart},
  verifiedThrough: ${table.verifiedThrough},
  years: [
${rows}
  ],
};
`;
}

function sum(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const source = JSON.parse(
    readFileSync(resolve(root, 'data/bikram-sambat.json'), 'utf8'),
  ) as SourceTable;
  const output = renderTable(buildTable(source));
  const target = resolve(root, 'packages/core/src/bs/data/years.ts');

  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // Missing file counts as out of date.
    }
    if (current !== output) {
      console.error(
        '✖ packages/core/src/bs/data/years.ts is out of date. Run `pnpm gen:data`.',
      );
      process.exit(1);
    }
    console.log('✔ BS data file is up to date');
  } else {
    writeFileSync(target, output);
    console.log(`✔ Wrote ${target}`);
  }
}
